import https from 'node:https';
import { ReferenceRepo } from './types.js';

interface GitHubContentItem {
  name: string;
  type: string;
  path: string;
}

function fetchGitHub(urlPath: string, token?: string): Promise<{ status: number; data: string }> {
  return new Promise((resolve) => {
    const headers: Record<string, string> = {
      'User-Agent': 'codendeploy-harvester/1.0',
      'Accept': 'application/vnd.github.v3+json',
    };
    if (token) {
      headers['Authorization'] = `token ${token}`;
    }

    const req = https.get(`https://api.github.com${urlPath}`, { headers }, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        resolve({ status: res.statusCode || 500, data });
      });
    });

    req.on('error', (err) => {
      resolve({ status: 500, data: err.message });
    });

    req.setTimeout(8000, () => {
      req.destroy();
      resolve({ status: 408, data: 'Timeout fetching GitHub API' });
    });
  });
}

/**
 * Harvests architectural patterns and directory topologies from reference repositories
 * to prevent domain prior failure in agentic code generation.
 */
export async function harvestReferenceArchitecture(
  referenceRepos: ReferenceRepo[],
  githubToken?: string
): Promise<string> {
  if (!referenceRepos || referenceRepos.length === 0) {
    return '';
  }

  let doc = `# Reference Architecture & Inspiration Invariants\n\n`;
  doc += `> Auto-generated by codendeploy referenceHarvester. These patterns define verified systems architectures extracted from canonical open-source implementations to prevent architectural misclassification.\n\n`;

  for (const ref of referenceRepos) {
    console.log(`🔍 [Reference Ingestion] Auditing reference repository: ${ref.ownerRepo}...`);
    doc += `## 📦 Reference: ${ref.ownerRepo}\n`;
    doc += `* **Purpose:** ${ref.description}\n`;
    if (ref.keyPatternsToExtract && ref.keyPatternsToExtract.length > 0) {
      doc += `* **Target Architectural Patterns:**\n`;
      for (const p of ref.keyPatternsToExtract) {
        doc += `  - ${p}\n`;
      }
    }
    doc += `\n`;

    // 1. Audit top-level contents
    const contentsRes = await fetchGitHub(`/repos/${ref.ownerRepo}/contents`, githubToken);
    if (contentsRes.status === 200) {
      try {
        const items = JSON.parse(contentsRes.data) as GitHubContentItem[];
        doc += `### Directory Topology Snapshot\n\`\`\`\n`;
        for (const item of items) {
          doc += `${item.type === 'dir' ? '📁' : '📄'} ${item.name}\n`;
        }
        doc += `\`\`\`\n\n`;
      } catch {}
    }

    // 2. Fetch CLAUDE.md or architectural guide if available
    const claudeRes = await fetchGitHub(`/repos/${ref.ownerRepo}/contents/CLAUDE.md`, githubToken);
    if (claudeRes.status === 200) {
      try {
        const fileObj = JSON.parse(claudeRes.data);
        if (fileObj.content) {
          const decoded = Buffer.from(fileObj.content, 'base64').toString('utf8');
          doc += `### Architectural Guidelines (Extracted from ${ref.ownerRepo}/CLAUDE.md)\n\n`;
          doc += `${decoded.slice(0, 3500)}\n\n`;
        }
      } catch {}
    } else {
      // Fallback: check README.md
      const readmeRes = await fetchGitHub(`/repos/${ref.ownerRepo}/contents/README.md`, githubToken);
      if (readmeRes.status === 200) {
        try {
          const fileObj = JSON.parse(readmeRes.data);
          if (fileObj.content) {
            const decoded = Buffer.from(fileObj.content, 'base64').toString('utf8');
            doc += `### Project Overview (Extracted from README.md)\n\n`;
            doc += `${decoded.slice(0, 2000)}\n\n`;
          }
        } catch {}
      }
    }

    doc += `---\n\n`;
  }

  doc += `## 🛡️ Critical Implementation Invariants for AI Coding Agents\n\n`;
  doc += `1. **In-Memory Virtual State Simulation**: NEVER spawn OS-level child processes (\`child_process.exec\`) for sandboxed educational command simulations. Implement pure JavaScript/TypeScript state machines (e.g. Virtual Git engine, Virtual Event Loop call stack arrays).\n`;
  doc += `2. **State Diff Evaluation**: Validate user progress by comparing the current in-memory AST/state tree against a declared target goal tree, rather than relying on brittle raw text/regex matching.\n`;
  doc += `3. **Decoupled Visual Rendering**: Keep visualization (SVG / Canvas / React components) reactive to state changes rather than hardcoding visual state transitions into command handlers.\n`;

  return doc;
}
